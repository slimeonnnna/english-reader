// 合并词库
const DICTIONARY = Object.assign({}, OFFLINE_DICTIONARY, COMMON_ADDITIONS);

/**
 * 离线词典查询引擎 (Dictionary Engine)
 * 具备多层回退机制与智能形态推导
 */
const DictEngine = {
  // 用户自定义词条 (保存在 localStorage)
  customDict: {},

  init() {
    try {
      const saved = localStorage.getItem("english_reader_custom_dict");
      if (saved) {
        this.customDict = JSON.parse(saved);
      }
    } catch (e) {
      console.warn("加载自定义词典失败:", e);
    }
  },

  saveCustomDict() {
    try {
      localStorage.setItem("english_reader_custom_dict", JSON.stringify(this.customDict));
    } catch (e) {
      console.warn("保存自定义词典失败:", e);
    }
  },

  addCustomWord(word, phonetic, definition) {
    const key = word.toLowerCase().trim();
    this.customDict[key] = [phonetic || `/${key}/`, definition];
    this.saveCustomDict();
  },

  /**
   * 核心查词函数
   * @param {string} rawWord - 用户点击的单词
   * @returns {object} { found: boolean, query: string, lemma: string, phonetic: string, translation: string, isStemmed: boolean, rule: string }
   */
  lookup(rawWord) {
    if (!rawWord) return null;
    const clean = rawWord.toLowerCase().replace(/^[^a-zA-Z]+|[^a-zA-Z]+$/g, "");
    if (!clean) return null;

    // 1. 用户自定义词典优先
    if (this.customDict[clean]) {
      const [ph, def] = this.customDict[clean];
      return {
        found: true,
        query: clean,
        lemma: clean,
        phonetic: ph,
        translation: def,
        isStemmed: false,
        source: "自定义词典"
      };
    }

    // 2. 内置词库精确匹配
    if (DICTIONARY[clean]) {
      const [ph, def] = DICTIONARY[clean];
      return {
        found: true,
        query: clean,
        lemma: clean,
        phonetic: ph,
        translation: def,
        isStemmed: false,
        source: "本地核心词典"
      };
    }

    // 3. 词形还原候选推导 (借助 stemmer.js)
    if (window.Stemmer && typeof window.Stemmer.getLemmaCandidates === "function") {
      const candidates = window.Stemmer.getLemmaCandidates(clean);
      for (const cand of candidates) {
        // 先检查自定义词典
        if (this.customDict[cand.form]) {
          const [ph, def] = this.customDict[cand.form];
          return {
            found: true,
            query: clean,
            lemma: cand.form,
            phonetic: ph,
            translation: def,
            isStemmed: true,
            rule: cand.rule,
            source: "词形还原匹配"
          };
        }
        // 再检查内置词典
        if (DICTIONARY[cand.form]) {
          const [ph, def] = DICTIONARY[cand.form];
          return {
            found: true,
            query: clean,
            lemma: cand.form,
            phonetic: ph,
            translation: def,
            isStemmed: true,
            rule: cand.rule,
            source: "词形还原匹配"
          };
        }
      }
    }

    // 4. 未收录单词回退处理（允许用户一键补充释义）
    return {
      found: false,
      query: clean,
      lemma: clean,
      phonetic: `/${clean}/`,
      translation: "暂未收录该词释义（点击下方按钮可手动添加或编辑此词）",
      isStemmed: false,
      source: "未收录"
    };
  }
};

// 初始化词典
DictEngine.init();
window.DictEngine = DictEngine;
window.DICTIONARY = DICTIONARY;
